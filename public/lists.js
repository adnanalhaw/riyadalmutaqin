  function fill(root) {
    (root || document).querySelectorAll("select[data-list]").forEach(function (sel) {
      if (sel.getAttribute("data-filled")) return;
      var arr = map[sel.getAttribute("data-list")] || [];
      var ph = sel.getAttribute("data-placeholder") || "اختر…";
      var cur = sel.getAttribute("data-value") || "";
      sel.innerHTML = '<option value="">' + ph + "</option>" +
        arr.map(function (x) {
          return '<option value="' + x + '"' + (x === cur ? " selected" : "") + ">" + x + "</option>";
        }).join("");
      sel.setAttribute("data-filled", "1");
    });
  }

  if (document.readyState !== "loading") fill();
  else document.addEventListener("DOMContentLoaded", function () { fill(); });

